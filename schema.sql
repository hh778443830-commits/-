-- SHUAIBIYA database schema. Run in Supabase SQL Editor.
create extension if not exists pgcrypto;
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'orders_monitor' check (role in ('admin','staff','orders_monitor')),
  assigned_category text check (assigned_category is null or assigned_category in ('ملابس','مفروشات','تجميل','بهارات','أدوات منزلية')),
  created_at timestamptz not null default now()
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('ملابس','مفروشات','تجميل','بهارات','أدوات منزلية')),
  price numeric(12,2) not null check (price >= 0),
  old_price numeric(12,2), tag text default '',
  colors text[] not null default array['متوفر'], sizes text[] not null default array['مقاس موحد'],
  image_url text, active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(), customer_name text not null,
  customer_phone text not null, address text, map_url text,
  total numeric(12,2) not null check(total >= 0),
  payment_method text not null default 'cash_on_delivery' check(payment_method='cash_on_delivery'),
  status text not null default 'new' check(status in ('new','confirmed','preparing','shipped','delivered','cancelled')),
  created_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null, unit_price numeric(12,2) not null,
  quantity integer not null check(quantity > 0), selected_color text, selected_size text
);
create or replace function public.current_role() returns text language sql stable security definer set search_path=public as $$
 select role from public.profiles where id=auth.uid()
$$;
create or replace function public.current_category() returns text language sql stable security definer set search_path=public as $$
 select assigned_category from public.profiles where id=auth.uid()
$$;
-- Create a safe default profile whenever an Auth user is created.
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,full_name,role) values(new.id,coalesce(new.raw_user_meta_data->>'full_name',''),'orders_monitor');
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
drop policy if exists "public read active products" on public.products;
create policy "public read active products" on public.products for select to anon, authenticated using (active=true or public.current_role() in ('admin','staff'));
drop policy if exists "staff manage assigned products" on public.products;
create policy "staff manage assigned products" on public.products for all to authenticated using (public.current_role()='admin' or (public.current_role()='staff' and category=public.current_category())) with check (public.current_role()='admin' or (public.current_role()='staff' and category=public.current_category()));
drop policy if exists "customers create orders" on public.orders;
create policy "customers create orders" on public.orders for insert to anon, authenticated with check (status='new' and payment_method='cash_on_delivery');
drop policy if exists "admin monitor read orders" on public.orders;
create policy "admin monitor read orders" on public.orders for select to authenticated using (public.current_role() in ('admin','orders_monitor'));
drop policy if exists "admin update orders" on public.orders;
create policy "admin update orders" on public.orders for update to authenticated using (public.current_role() in ('admin','orders_monitor')) with check (public.current_role() in ('admin','orders_monitor'));
drop policy if exists "customer create order items" on public.order_items;
create policy "customer create order items" on public.order_items for insert to anon, authenticated with check (exists(select 1 from public.orders o where o.id=order_id and o.status='new'));
drop policy if exists "admin read order items" on public.order_items;
create policy "admin read order items" on public.order_items for select to authenticated using (public.current_role() in ('admin','orders_monitor'));
drop policy if exists "admin manage profiles" on public.profiles;
create policy "admin manage profiles" on public.profiles for all to authenticated using (public.current_role()='admin') with check (public.current_role()='admin');
drop policy if exists "users read own profile" on public.profiles;
create policy "users read own profile" on public.profiles for select to authenticated using (id=auth.uid() or public.current_role()='admin');
